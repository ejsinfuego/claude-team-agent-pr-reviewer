#!/usr/bin/env bash
# Reviewer Script: performs one Review end-to-end for a single PR.
# Usage: review-pr.sh <owner/repo> <pr-number>
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "Usage: $0 <owner/repo> <pr-number>" >&2
  exit 1
fi

REPO="$1"
PR_NUMBER="$2"

WORKDIR=$(mktemp -d)
trap 'rm -rf "$WORKDIR"' EXIT

DIFF_FILE="$WORKDIR/diff.patch"
PROMPT_FILE="$WORKDIR/prompt.txt"
REVIEW_FILE="$WORKDIR/review.txt"

gh pr diff "$PR_NUMBER" --repo "$REPO" > "$DIFF_FILE"

VIEW_JSON=$(gh pr view "$PR_NUMBER" --repo "$REPO" --json title,body,comments)
TITLE=$(jq -r '.title' <<< "$VIEW_JSON")
BODY=$(jq -r '.body // "(no description)"' <<< "$VIEW_JSON")
COMMENTS=$(jq -r '
  (.comments // []) |
  if length == 0 then "(none)"
  else (map("- " + .author.login + ": " + .body) | join("\n"))
  end
' <<< "$VIEW_JSON")

{
  echo "You are reviewing GitHub pull request #$PR_NUMBER in $REPO."
  echo "Give a concise, constructive code review: call out bugs, risks, and concrete improvements. Do not repeat points already made in the existing discussion below."
  echo
  echo "## Title"
  echo "$TITLE"
  echo
  echo "## Description"
  echo "$BODY"
  echo
  echo "## Existing discussion"
  echo "$COMMENTS"
  echo
  echo "## Diff"
  echo '```diff'
  cat "$DIFF_FILE"
  echo '```'
} > "$PROMPT_FILE"

claude -p --allowedTools "" < "$PROMPT_FILE" > "$REVIEW_FILE"

if [[ ! -s "$REVIEW_FILE" ]]; then
  echo "claude produced an empty review for $REPO#$PR_NUMBER" >&2
  exit 1
fi

{
  echo "_Automated review generated by Claude._"
  echo
  cat "$REVIEW_FILE"
} > "$WORKDIR/final_review.txt"

gh pr review "$PR_NUMBER" --repo "$REPO" --comment --body-file "$WORKDIR/final_review.txt"
